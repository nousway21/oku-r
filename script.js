// Cinematic Preloader
window.addEventListener("DOMContentLoaded", () => {
  const preloader = document.getElementById("preloader");
  const progress = document.getElementById("loader-progress");
  const percent = document.getElementById("loader-percent");
  const loaderText = document.getElementById("loader-text");

  const steps = [
    "LOADING RUZEN VECTOR...",
    "MOUNTING SECURITY MODULES...",
    "SYNCING PORTFOLIO DATA...",
    "READY."
  ];

  let val = 0;
  const interval = setInterval(() => {
    val += Math.floor(Math.random() * 18) + 10;
    if (val >= 100) {
      val = 100;
      clearInterval(interval);
      loaderText.textContent = steps[3];
      setTimeout(() => preloader.classList.add("fade-out"), 280);
    } else if (val > 65) {
      loaderText.textContent = steps[2];
    } else if (val > 30) {
      loaderText.textContent = steps[1];
    }
    progress.style.width = val + "%";
    percent.textContent = val + "%";
  }, 90);
});

// Subtle Parallax for Background White Logo
const bgLogo = document.getElementById("bg-ruzen-logo");
window.addEventListener("mousemove", (e) => {
  const x = (e.clientX / window.innerWidth - 0.5) * 24;
  const y = (e.clientY / window.innerHeight - 0.5) * 24;
  bgLogo.style.transform = `translate3d(${x}px, ${y}px, 0) scale(1.02)`;
});

// Language Switcher
const langBtns = document.querySelectorAll(".lang-btn");
langBtns.forEach((btn) => {
  btn.addEventListener("click", () => {
    langBtns.forEach((b) => b.classList.remove("active"));
    btn.classList.add("active");
    const lang = btn.dataset.lang;
    const dict = translations[lang];
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.dataset.i18n;
      if (dict[key]) el.textContent = dict[key];
    });
  });
});

// Project Modal
const modal = document.getElementById("project-modal");
const modalTitle = document.getElementById("modal-title");
const modalTech = document.getElementById("modal-tech");
const modalDesc = document.getElementById("modal-desc");
const modalClose = document.getElementById("modal-close");

document.querySelectorAll(".project-card").forEach((card) => {
  card.addEventListener("click", () => {
    const idx = Number(card.dataset.project);
    const item = projectDetails[idx];
    modalTitle.textContent = item.title;
    modalTech.textContent = item.tech;
    modalDesc.textContent = item.desc;
    modal.classList.remove("hidden");
  });
});

modalClose.addEventListener("click", () => modal.classList.add("hidden"));
modal.querySelector(".modal-backdrop").addEventListener("click", () => modal.classList.add("hidden"));
